import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
function moduleBody(file) {
  return read(file).replace(/^import .* from '@hermes\/plugin-sdk'\r?\n/gm, '')
    .replace(/export (const|function) /g, '$1 ').replace('export default {', 'return {')
}
function component(file) {
  return moduleBody(file).replace(/function botModeChatVisible\(\) \{[\s\S]*?\n\}/,
    `function botModeChatVisible() {
  const canonical = document.body.getAttribute('data-inner-circle-canonical')
  return Boolean(canonical && canonical === host.state.focusedStoredSessionId?.get?.())
}`)
    .replaceAll('[data-chat-surface]', '[data-chat-surface][data-inner-circle-chat]')
}
const bundle = `// Generated by scripts/build.mjs; edit the readable sources, then rebuild.
// Contains MIT-licensed Hermes Bot Kit components; see LICENSE and vendor/README.md.
import { PALETTE_AREA, THEMES_AREA, requestTheme, host, queryClient, coarseElapsed, translateNow } from '@hermes/plugin-sdk'
const quiet = (() => {${component('vendor/bubble-mode.js')}\n})()
const tasks = (() => {${component('vendor/task-dock.js')}\n})()
${read('src/timeline.js').replace(/export (const|function) /g, '$1 ')}
const appearance = (() => {${moduleBody('plugin.js')}\n})()
function componentContext(ctx, name) {
  return {...ctx,
    register: contribution => ctx.register({...contribution, id: name + '.' + contribution.id,
      data: contribution.data?.id ? {...contribution.data, id: 'inner-circle.' + contribution.data.id} : contribution.data}),
    storage: {get: (key, fallback) => ctx.storage.get(name + '.' + key, fallback),
      set: (key, value) => ctx.storage.set(name + '.' + key, value)}
  }
}
export default {
  ...appearance, id: 'inner-circle', name: 'Inner Circle',
  description: 'My personal bot-centric Hermes setup: portraits, sage chat and folded activity.',
  register(ctx) {
    quiet.register(componentContext(ctx, 'quiet'))
    tasks.register(componentContext(ctx, 'tasks'))
    appearance.register(ctx)
    const timeline = createTimeline(ctx, host)
    ctx.onDispose(() => timeline.dispose())
  }
}
`
const target = path.join(root, 'desktop/plugin.js')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== bundle) throw new Error('Run npm run build; the shipped bundle is stale')
} else fs.writeFileSync(target, bundle)
